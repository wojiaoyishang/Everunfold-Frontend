export function defaultWorkspaceLayout(
  cards: readonly WorkspaceCardDefinition[],
): WorkspaceCardPlacement[] {
  return cards
    .filter((card) => card.defaultVisible !== false)
    .map((card) => ({ id: card.id, width: card.width ?? 3 }));
}
